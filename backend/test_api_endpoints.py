def test_fallback_endpoint():
    print("\n--- TEST 4: Fallback for Unknown Questions ---")
    start = time.perf_counter()
    response = client.post("/chat", json={"question": "What is the recipe for chocolate cake?"})
    elapsed = time.perf_counter() - start

    assert response.status_code == 200
    data = response.json()
    print(f"Execution time:  {elapsed:.5f}s")
    print(f"Answer snippet:  {data.get('answer')[:120]}...")
